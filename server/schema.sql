CREATE TABLE IF NOT EXISTS world_users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, avatar TEXT NOT NULL DEFAULT '',
 color TEXT NOT NULL DEFAULT '#cf7aff', banned INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS world_sessions (
 digest TEXT PRIMARY KEY, user_id TEXT NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS world_plots (
 id INTEGER PRIMARY KEY, owner TEXT UNIQUE, name TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS world_objects (
 id TEXT PRIMARY KEY, plot INTEGER NOT NULL, kind TEXT NOT NULL,
 x INTEGER NOT NULL, z INTEGER NOT NULL, rotation INTEGER NOT NULL,
 UNIQUE(plot,x,z)
);
