CREATE TABLE IF NOT EXISTS world_users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, avatar TEXT NOT NULL DEFAULT '',
 color TEXT NOT NULL DEFAULT '#cf7aff', banned INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS world_sessions (
 digest TEXT PRIMARY KEY, user_id TEXT NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS world_plots (
 id INTEGER PRIMARY KEY, owner TEXT UNIQUE, name TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS world_objects (
 id TEXT PRIMARY KEY, plot INTEGER NOT NULL, kind TEXT NOT NULL,
 x INTEGER NOT NULL, z INTEGER NOT NULL, rotation INTEGER NOT NULL,
 UNIQUE(plot,x,z)
);

CREATE TABLE IF NOT EXISTS world_wallets(user_id TEXT PRIMARY KEY,balance INTEGER NOT NULL DEFAULT 0 CHECK(balance>=0));
CREATE TABLE IF NOT EXISTS world_ledger(event TEXT PRIMARY KEY,user_id TEXT NOT NULL,amount INTEGER NOT NULL,reason TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS world_activity(user_id TEXT NOT NULL,day TEXT NOT NULL,seconds INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(user_id,day));

CREATE TABLE IF NOT EXISTS world_inventory(user_id TEXT PRIMARY KEY,fish INTEGER NOT NULL DEFAULT 0 CHECK(fish>=0),dance INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS world_fishing(user_id TEXT PRIMARY KEY,cast_id TEXT NOT NULL,ready INTEGER NOT NULL,expires INTEGER NOT NULL,next_cast INTEGER NOT NULL,claimed INTEGER NOT NULL DEFAULT 0);
